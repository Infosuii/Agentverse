describe('ReportTab', () => {
  it('renders report markdown, key figures with provenance popover, download link, and print button', () => {
    const queryClient = new QueryClient({
      defaultOptions: { queries: { retry: false } },
    });
    const analysis = buildMockAnalysis();
    const printSpy = vi.spyOn(window, 'print').mockImplementation(() => {});

    render(
      <QueryClientProvider client={queryClient}>
        <MemoryRouter>
          <ReportTab analysis={analysis} />
        </MemoryRouter>
      </QueryClientProvider>,
    );

    expect(
      screen.getAllByText(/Policy Assessment: Raise the CT main rate from 25% to 28%/i).length,
    ).toBeGreaterThanOrEqual(1);
    expect(screen.getByText(/Generated by: Template/i)).toBeInTheDocument();

    // Check Download .md link
    const downloadLink = screen.getByRole('link', { name: /Download \.md/i });
    expect(downloadLink).toHaveAttribute('href', '/api/analyses/A-REP-01/report.md');

    // Click Print / Save as PDF button
    const printBtn = screen.getByRole('button', { name: /Print \/ Save as PDF/i });
    fireEvent.click(printBtn);
    expect(printSpy).toHaveBeenCalledOnce();
    printSpy.mockRestore();

    // Click key figure to open provenance popover
    const figBtn = screen.getByRole('button', { name: '+£5.20bn' });
    fireEvent.click(figBtn);

    expect(screen.getByText('STEP-CENTRAL-2027-28-BEHAV')).toBeInTheDocument();
    const calcInspectorLink = screen.getByRole('link', { name: /Open in Calculation Inspector/i });
    expect(calcInspectorLink).toHaveAttribute(
      'href',
      '/analyses/A-REP-01/assumptions?metric=revenue_behavioural_gbp_bn&year=2027-28',
    );
  });
});
